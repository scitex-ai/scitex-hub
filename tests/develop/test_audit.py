"""Audit conformance — runs `scitex-dev ecosystem audit-all` on this
package as a normal pytest test. Generated by
`scitex-dev ecosystem write-audit-test`. Re-run that command after
upgrading scitex-dev to refresh any pin in [dev].

This is the BRAND-QUALITY GATE for scitex-hub. Every entry in
``skip_rules`` below is a documented deferral, not a silent skip:
each rule id has a one-line rationale and a tracking marker (`TODO`,
or an explicit external campaign name). When the audit-cli rule
corpus drifts, unknown rules should SURFACE as failures here — that
is the gate's job.

Do NOT mark this test ``@pytest.mark.e2e`` or otherwise bypass it
from the headless pytest-matrix run. The silent-skip pattern is what
this test exists to prevent.

TWO GUARDS KEEP THIS GATE HONEST, because "the audit passed" and "the
audit passed with N known violations suppressed" look identical in CI:

  * A MISSING CORPUS IS A FAILURE, NOT A SKIP. `scitex-dev` absent used
    to `pytest.skip`, which turned the whole gate into a no-op whenever
    the pip resolve hiccuped — invisibly, because a skipped test is
    green. It now fails with an actionable hint.
  * THE MASK IS RATCHETED. ``test_masked_violation_count_within_ceiling``
    asserts the suppressed-violation count never exceeds
    ``MAX_MASKED_VIOLATIONS``, so the deferral list can shrink but not
    quietly grow.

Bypass (exceptions / temporal remedy only):
    SCITEX_DEV_SKIP_AUDIT=1 python -m pytest .

Use ONLY when remediating pre-existing violations or developing
without the audit corpus available locally. CI for release branches
MUST NOT set this — drift goes silent.
"""

import os
import re
import shutil
import warnings
from pathlib import Path

import pytest

# Ceiling on the number of violations `skip_rules` is allowed to mask.
# This may only ever DECREASE. Raising it is not a fix — it is the mask
# growing. Lower it as the deferral campaigns below land; if a change
# genuinely needs a new skip_rules entry, the ceiling stays put and
# something else must come off the list first.
#
# SLACK NOTICE, 2026-08-10: the corpus pin moved to scitex-dev==0.43.1, which
# demotes ~100 CLI-convention findings from error to warning and stops
# counting warn-tier notices at all. The mask measured 49 here (py3.12, full
# `.[all,dev]` install) against this ceiling of 151 — so the ratchet currently
# has ~100 of slack and is not actually ratcheting anything. Deliberately NOT
# tightened in the same change that moved the corpus: 49 is one measurement on
# one interpreter, and pytest-matrix runs 3.11/3.12/3.13, where the audit-cli
# leg depends on which optional imports succeed. Tighten this to just above the
# highest of the THREE legs once a green matrix run has reported them — do not
# guess it from this one number.
MAX_MASKED_VIOLATIONS = 151

_MASKED_COUNT_RE = re.compile(r"audit-all:\s*(\d+)\s+violation\(s\)\s+masked")

# Documented deferrals. Every entry carries a written rationale and a
# tracking campaign — per the rule that exemptions are taken one at a
# time in a reviewable file, never with a blanket flag that silences the
# whole run.
# Documented deferrals now live in `.scitex/dev/config.yaml` under
# `audit.skip-rules`, and are READ FROM THERE rather than restated here.
#
# WHY THE MOVE (measured on PR #683, scitex-dev 0.56.4, 2026-08-23):
# this used to be a literal tuple handed to `audit_all_for_package(...,
# skip_rules=...)`. That only ever worked while scitex-dev graded
# in-process. Newer scitex-dev shells out to its own CLI —
#
#     python -m scitex_dev ecosystem audit-all scitex-hub --path <repo>
#
# — with no skip-rules argument, so the tuple never reached the auditor.
# Every declared deferral came back as an unmasked error and the run
# reported `0 masked by skip-rules (0 declared)`: 47 unmasked errors, and
# the ONLY two red checks in a run of 4577 passing tests. That is also
# precisely what hub's `scitex-dev==0.43.1` pin was holding off, which is
# why the pin could not become a floor until this moved.
#
# The config file is on disk, so the shelled-out CLI reads it directly and
# the deferrals no longer depend on which scitex-dev is resolved. Measured
# after the move, same version: `0 unmasked error(s), 41 masked by
# skip-rules (20 declared)`.
#
# Reading them back here keeps ONE source of truth: the in-process path
# and the CLI path cannot disagree, because there is only one list.
def _declared_skip_rules():
    """Rule ids declared in `.scitex/dev/config.yaml` -> `audit.skip-rules`."""
    import yaml

    config = Path(__file__).resolve().parents[2] / ".scitex" / "dev" / "config.yaml"
    entries = yaml.safe_load(config.read_text())["audit"]["skip-rules"]
    return tuple(entry["rule"] for entry in entries)


SKIP_RULES = _declared_skip_rules()


def _require_audit_tooling():
    """Fail loudly when the audit corpus is absent.

    A missing ``scitex-dev`` previously produced ``pytest.skip``, which
    reports green. That made a pip-resolution hiccup silently delete the
    gate — the same shape as a wrapper that swallows a non-zero exit and
    returns 0. Absence is now a failure with the next step named; the
    only way past is the documented, explicit env bypass.
    """
    if shutil.which("scitex-dev") is not None:
        return
    if os.environ.get("SCITEX_DEV_SKIP_AUDIT") == "1":
        pytest.skip("SCITEX_DEV_SKIP_AUDIT=1 set — audit deliberately bypassed")
    pytest.fail(
        "scitex-dev is not installed, so the brand-quality gate cannot run "
        "and this test must not report success.\n"
        "Fix: pip install 'scitex-dev[cli-audit]' — it belongs in "
        "[project.optional-dependencies.dev]; check it is still listed "
        "there and that the CI install step did not fail silently.\n"
        "To bypass deliberately while remediating locally, set "
        "SCITEX_DEV_SKIP_AUDIT=1. CI for release branches MUST NOT set it."
    )


@pytest.fixture(scope="module")
def audit_masked_count():
    """Run the audit ONCE for this module; yield the masked-violation count.

    ``audit_all_for_package`` raises AssertionError on any violation that
    matches no entry in ``SKIP_RULES``, so an unrecognized rule fails
    every test in this module — unknown rules surfacing as failures is
    the gate's job.

    The count is ``None`` when the installed scitex-dev emits no
    masked-count warning. That is UNKNOWN, and the tests below treat it
    as a failure rather than collapsing it into zero: "I could not tell"
    must never silently become "nothing was masked".
    """
    _require_audit_tooling()
    from scitex_dev.testing import audit_all_for_package

    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        # audit-all walks every sub-auditor; cold CI runs (pip resolve
        # + corpus load) can exceed the 120 s default. Give headroom.
        #
        # `path=` is NOT optional here. Without it audit-all resolves its
        # target from the CWD, and scitex-dev's own warning says that then
        # "grades the WRONG tree and still reports a confident pass/fail".
        # Hub's CI runs on shared self-hosted runners that can hold sibling
        # checkouts, which is exactly the case that warning names. Anchor to
        # this file instead: parents[2] is the repo root from
        # tests/develop/test_audit.py (develop -> tests -> root).
        audit_all_for_package(
            "scitex-hub",
            path=Path(__file__).resolve().parents[2],
            timeout=600.0,
            skip_rules=SKIP_RULES,
        )

    for record in caught:
        match = _MASKED_COUNT_RE.search(str(record.message))
        if match:
            yield int(match.group(1))
            return
    yield None


def test_audit_all_clean(audit_masked_count):
    """audit-all completes with no unrecognized violation and a known mask."""
    # Arrange: the fixture ran audit-all, raising on any unrecognized rule.
    expected_determinate_mask = True
    # Act
    got_determinate_mask = audit_masked_count is not None
    # Assert
    assert got_determinate_mask == expected_determinate_mask, (
        "audit-all passed but its masked-violation count could not be read, "
        "so this gate cannot say whether it is green or merely quiet. The "
        "installed scitex-dev no longer emits the 'audit-all: N "
        "violation(s) masked' warning that _MASKED_COUNT_RE parses — update "
        "the pattern to match the new format."
    )


def test_masked_violation_count_within_ceiling(audit_masked_count):
    """The deferral mask never grows beyond ``MAX_MASKED_VIOLATIONS``."""
    # Arrange
    ceiling = MAX_MASKED_VIOLATIONS
    # Act
    masked = audit_masked_count
    # Assert
    assert masked is not None and masked <= ceiling, (
        f"masked violations = {masked} (ceiling {ceiling}). The deferral "
        "list grew: fix the violations, or trade an existing SKIP_RULES "
        "entry out so the total does not rise. Do not raise the ceiling — "
        "that is the mask growing, not the gate passing."
    )


def test_every_declared_deferral_states_a_reason():
    """A deferral that cannot say why is the abandonment this list catches.

    The auditor rejects a reasonless entry loudly, so this only fails when
    the file is edited without running an audit — which is exactly when a
    bare rule id would otherwise slip in. It also guards the shape
    `_declared_skip_rules` depends on: a plain string entry (the shorthand
    mapping form) parses fine as YAML and would raise TypeError there.
    """
    # Arrange
    import yaml

    config = Path(__file__).resolve().parents[2] / ".scitex" / "dev" / "config.yaml"
    entries = yaml.safe_load(config.read_text())["audit"]["skip-rules"]
    # Act
    reasonless = [
        entry for entry in entries
        if not isinstance(entry, dict) or not str(entry.get("reason", "")).strip()
    ]
    # Assert
    assert reasonless == [], (
        f"skip-rules entries with no written rationale: {reasonless}. Every "
        "deferral must say why, in writing, next to the rule it defers."
    )
